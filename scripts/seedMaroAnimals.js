async function seedMaroAnimals() {
    if (!process.env.MONGO_URI) throw new Error("MONGO_URI is missing from .env");
    await mongoose.connect(process.env.MONGO_URI);

    const addedNames = [];
    const updatedNames = [];
    for (const animal of maroAnimals) {
        const result = await Animal.findOneAndUpdate(
            { name: animal.name },
            { $set: { ...MARO_DEFAULTS, ...animal } },
            { upsert: true, setDefaultsOnInsert: true, runValidators: true, includeResultMetadata: true }
        );
        (result.lastErrorObject?.updatedExisting ? updatedNames : addedNames).push(animal.name);
    }

    console.log(`Added ${addedNames.length}: ${addedNames.join(", ") || "none"}`);
    console.log(`Updated ${updatedNames.length}: ${updatedNames.join(", ") || "none"}`);
}

seedMaroAnimals()
    .catch((error) => {
        console.error("MARO animal seed failed:", error.message);
        process.exitCode = 1;
    })
    .finally(() => mongoose.disconnect());
